import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.env.BELAVISTA_ROOT;
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
test('HTML carrega tela de loading',()=>{const h=read('public-leads.html');assert.match(h,/public-model-loading-v53\.css/);assert.match(h,/public-model-loading-v53\.mjs/);});
test('loader inicia 3D deferido',()=>{const j=read('public-model-loading-v53.mjs');assert.match(j,/startPublic3D/);assert.match(j,/scheduleThree/);});
test('loader usa progresso real do model',()=>{const j=read('public-model-loading-v53.mjs');assert.match(j,/dataset\?\.modelProgress|dataset\.modelProgress/);assert.match(j,/model-ready/);});
test('fallback não prende a página',()=>{const j=read('public-model-loading-v53.mjs');assert.match(j,/Continuar com a base estática/);assert.match(j,/data-loader-continue/);});
test('visual branded existe',()=>{const c=read('public-model-loading-v53.css');assert.match(c,/BELAVISTA_PUBLIC_MODEL_LOADING_V53/);assert.match(c,/public-model-loading__plan/);});
