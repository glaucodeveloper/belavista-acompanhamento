import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {readFile} from 'node:fs/promises';
import {chromium} from 'playwright';

const token = process.env.ALIANCAPARK_SESSION_TOKEN;
const image = process.env.ALIANCAPARK_EXAMPLE_IMAGE;
const worker = (process.env.ALIANCAPARK_WORKER_URL || 'https://belavista-cloudflare-worker.icaroglaucooliveira.workers.dev').replace(/\/$/, '');
const expectedTotal = Number(process.env.ALIANCAPARK_EXPECTED_TOTAL || 2869.54);
const expectedDate = process.env.ALIANCAPARK_EXPECTED_DATE || '2025-02-18';
if (!token || !image) throw new Error('Defina ALIANCAPARK_SESSION_TOKEN e ALIANCAPARK_EXAMPLE_IMAGE.');
if (!Number.isFinite(expectedTotal) || expectedTotal < 0) throw new Error('ALIANCAPARK_EXPECTED_TOTAL deve ser um número válido.');
const originalWorker = 'https://belavista-cloudflare-worker.icaroglaucooliveira.workers.dev';
const port = Number(process.env.ALLOCATION_E2E_PORT || 5199);
const app = `http://127.0.0.1:${port}`;
const vite = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--config', 'vite.config.js', '--host', '127.0.0.1', '--port', String(port), '--strictPort'], {cwd: process.cwd(), stdio:'ignore'});
let browser;
try {
  let ready = false;
  for (let i=0;i<60;i++) { try { if ((await fetch(app)).ok) {ready=true;break;} } catch {} await new Promise(resolve=>setTimeout(resolve,250)); }
  if (!ready) throw new Error('A aplicação local não iniciou.');
  let data = {lots:[],materials:[],services:[],transfers:[],agenda:[],stages:JSON.parse(await readFile('frontend/src/data/archived-stage-seed.json','utf8')).stages};
  let revision = 0, syncReads = 0;
  browser = await chromium.launch({headless:true,...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
  const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.addInitScript(t=>sessionStorage.setItem('alianca-session-token',t),token);
  if (worker !== originalWorker) await page.route(`${originalWorker}/**`,async route=>{const source=new URL(route.request().url());await route.fulfill({response:await route.fetch({url:`${worker}${source.pathname}${source.search}`,timeout:120000})});});
  await page.route(`${originalWorker}/api/sync`, async route=>{if(route.request().method()==='GET'){syncReads++;return route.fulfill({json:{data,revision:`test-${revision}`}})}data=route.request().postDataJSON().data;revision++;return route.fulfill({json:{revision:`test-${revision}`}})});
  await page.goto(app);
  await page.getByRole('button',{name:'Assistente',exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(image);
  await page.locator('textarea').fill('Nota fiscal para Drenagem Pluvial. Registrar materiais.');
  await page.locator('button.send-button').click();
  await page.locator('.chat-message .outbox-status').getByText(/Processado|Falha no processamento/).waitFor({timeout:150000});
  assert.equal(await page.getByText('Nota fiscal para Drenagem Pluvial. Registrar materiais.',{exact:true}).count(),0,'A mensagem do usuário deve ficar fora da área de respostas.');
  assert.equal(await page.locator('.chat-message').count(),1);
  const reply = await page.locator('.chat-assistant-reply').innerText();
  assert.doesNotMatch(reply, /qual (?:lote|rua|quadra|área)|em qual (?:lote|rua|quadra|área)/i, 'O fluxo não deve exigir localização para a nota.');
  const selection = page.getByRole('button',{name:'Alocar',exact:true});
  if (!await selection.count()) throw new Error(`Seleção manual indisponível. Cartão: ${(await page.locator('.chat-message').innerText()).slice(0, 1200)}`);
  await selection.click();
  await page.getByRole('dialog',{name:'Confirmar alocação'}).waitFor();
  assert.equal(await page.locator('.catalog-material-picker button[type=submit]').count(), 0, 'A confirmação deve ficar fora das opções.');
  await page.locator('.catalog-material-form select').nth(0).selectOption({label:'Drenagem Pluvial'});
  await page.locator('.catalog-material-form select').nth(1).selectOption({label:'Assentar rede pluvial do trecho'});
  await page.locator('.catalog-material-form select').nth(2).selectOption({label:'Tubo/manilha de drenagem'});
  const noteDate = page.locator('.catalog-material-form input[type=date]');
  assert.equal(await noteDate.inputValue(), '', 'A interface não deve inventar uma data quando a leitura não a reconhece.');
  await noteDate.fill(expectedDate);
  await page.getByText('Categoria:', {exact:false}).first().waitFor();
  assert.match(await page.locator('.catalog-destination').innerText(), /Assentar rede pluvial do trecho/);
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  assert.equal(data.materials.length,0,'Cancelar não deve criar um registro.');
  await page.getByRole('button',{name:'Alocar',exact:true}).click();
  assert.match(await page.locator('.catalog-destination').innerText(), /Assentar rede pluvial do trecho/, 'A escolha deve permanecer disponível ao reabrir.');
  assert.equal(await page.locator('.catalog-material-form input').nth(2).inputValue(), expectedTotal.toLocaleString('pt-BR', {minimumFractionDigits:2, maximumFractionDigits:2}), 'O total da nota deve ser sugerido no modal.');
  const readsBeforeFirstSave = syncReads;
  await page.getByRole('button',{name:'Confirmar alocação'}).click();
  await page.getByText('Material escolhido registrado em Materiais.').waitFor({timeout:20000});
  assert.ok(syncReads > readsBeforeFirstSave, 'Após gravar, a aplicação deve reler o estado sincronizado.');
  assert.match(await page.locator('.material-destination-card').innerText(), /Categoria: Assentar rede pluvial do trecho/);
  assert.equal(data.materials.length,1);
  assert.equal(data.materials[0].name,'Tubo/manilha de drenagem');
  assert.equal(data.materials[0].stageName,'Drenagem Pluvial');
  assert.equal(data.materials[0].activityName,'Assentar rede pluvial do trecho');
  assert.equal(data.materials[0].amount,expectedTotal);
  assert.equal(data.materials[0].date,expectedDate);
  await page.getByRole('button',{name:'Materiais',exact:true}).click();
  await page.locator('.material-table').getByText('Tubo/manilha de drenagem').first().waitFor();
  assert.equal(await page.locator('.material-date-table').getByText('18/02/2025',{exact:true}).count(),1,'A tabela deve agrupar a nota pela data preenchida.');
  assert.equal(await page.locator('.material-period-table').getByText('Fevereiro de 2025',{exact:false}).count(),1,'A tabela deve agrupar a nota por período.');
  await page.getByLabel('Período dos gastos').selectOption({label:'Fevereiro de 2025'});
  assert.match(await page.locator('.material-invoice-metrics').innerText(),/2\.869,54/,'O total do período deve atualizar ao selecionar o mês.');
  await page.reload();
  await page.locator('.material-table').getByText('Tubo/manilha de drenagem').first().waitFor({timeout:15000});
  await page.getByRole('button',{name:'Assistente',exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(image);
  await page.locator('textarea').fill('Exemplo de nota fiscal para materiais sem alocação.');
  await page.locator('button.send-button').click();
  await page.locator('.chat-message .outbox-status').getByText(/Processado|Falha no processamento/).waitFor({timeout:150000});
  await page.getByRole('button',{name:'Alocar',exact:true}).click();
  for (const select of await page.locator('.catalog-material-form select').all()) assert.equal(await select.inputValue(), '', 'As escolhas devem iniciar vazias.');
  assert.equal(await page.locator('.catalog-material-form input').nth(2).inputValue(), expectedTotal.toLocaleString('pt-BR', {minimumFractionDigits:2, maximumFractionDigits:2}), 'O valor deve ser inferido mesmo sem uma alocação.');
  assert.equal(await page.locator('.catalog-material-form input[type=date]').inputValue(), '');
  await page.locator('.catalog-material-form input[type=date]').fill(expectedDate);
  const readsBeforeSecondSave = syncReads;
  await page.getByRole('button',{name:'Confirmar alocação'}).click();
  await page.getByText('Material escolhido registrado em Materiais.').waitFor({timeout:20000});
  assert.ok(syncReads > readsBeforeSecondSave, 'A inclusão sem escolhas também deve reler o estado sincronizado.');
  assert.equal(data.materials.length,2);
  assert.equal(data.materials[1].name,'Material não informado');
  assert.equal(data.materials[1].stageId,null);
  assert.equal(data.materials[1].activityId,null);
  assert.equal(data.materials[1].date,expectedDate);
  await page.getByRole('button',{name:'Materiais',exact:true}).click();
  await page.locator('.material-table').getByText('Material não informado').first().waitFor();
  await page.reload();
  await page.locator('.material-table').getByText('Material não informado').first().waitFor({timeout:15000});
  assert.deepEqual(errors,[],'A interface não deve ter erros de inicialização.');
  const viewport = await page.evaluate(()=>({body:document.documentElement.scrollWidth,viewport:innerWidth}));
  assert.ok(viewport.body<=viewport.viewport,'A tela não deve extrapolar a largura.');
  console.log('PASS nota real, drenagem e escolhas opcionais vazias, valor inferido, exibição e recarga em Materiais. Inferência real; persistência isolada.');
} finally {await browser?.close();vite.kill();}
